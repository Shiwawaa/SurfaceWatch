def _tr(lang: str) -> dict[str, str]:
    return _REPORT_STRINGS["fr"] if lang == "fr" else _REPORT_STRINGS["en"]


def _grade_label(score: int, lang: str) -> str:
    grade = risk_grade_label(score)
    return _GRADE_FR.get(grade, grade) if lang == "fr" else grade


def _sev_label(severity: str, lang: str) -> str:
    key = severity.lower()
    if lang == "fr":
        return _SEV_FR.get(key, severity.upper())
    return severity.upper()


def _safe_pdf_text(text: str) -> str:
    normalized = (
        str(text)
        .replace("\u2019", "'")
        .replace("\u2018", "'")
        .replace("\u201c", '"')
        .replace("\u201d", '"')
        .replace("\u2014", "-")
        .replace("\u2013", "-")
        .replace("\u0153", "oe")
        .replace("\u0152", "OE")
    )
    return normalized.encode("latin-1", errors="replace").decode("latin-1")


