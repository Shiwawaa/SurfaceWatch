import html
from datetime import datetime, timezone

from fpdf import FPDF

from models.domain import Domain, FindingRecord, Scan
from models.schemas import DiffOut
from services.risk_score import risk_grade_label


def _safe_pdf_text(text: str) -> str:
    return text.encode("latin-1", errors="replace").decode("latin-1")


def generate_html_report(
    domain: Domain,
    scan: Scan | None,
    findings: list[FindingRecord],
    diff: DiffOut,
) -> str:
    generated_at = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    score = scan.risk_score if scan else domain.latest_risk_score
    grade = risk_grade_label(score)

    rows_html = []
    for f in findings:
        rows_html.append(
            f"""
            <tr>
              <td><span class="sev sev-{html.escape(f.severity)}">{html.escape(f.severity.upper())}</span></td>
              <td><code>{html.escape(f.host)}</code></td>
              <td>{html.escape(f.scanner)}</td>
              <td>
                <strong>{html.escape(f.title)}</strong><br/>
                <small>{html.escape(f.explanation)}</small><br/>
                <small><em>Evidence:</em> {html.escape(f.evidence)}</small><br/>
                <small><em>Fix:</em> {html.escape(f.remediation)}</small>
              </td>
            </tr>
            """
        )

    findings_table = "\n".join(rows_html) or "<tr><td colspan='4'>No findings recorded yet.</td></tr>"

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <title>SurfaceWatch Security Report - {html.escape(domain.name)}</title>
  <style>
    body {{ font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", sans-serif; color: #0f172a; margin: 32px; line-height: 1.5; }}
    h1, h2 {{ margin: 0 0 8px 0; }}
    .meta {{ color: #475569; font-size: 13px; margin-bottom: 24px; }}
    .summary {{ display: flex; gap: 16px; margin-bottom: 24px; }}
    .card {{ border: 1px solid #cbd5e1; border-radius: 8px; padding: 12px 16px; min-width: 140px; }}
    .card .label {{ font-size: 12px; color: #64748b; }}
    .card .value {{ font-size: 22px; font-weight: 700; }}
    table {{ width: 100%; border-collapse: collapse; margin-top: 12px; }}
    th, td {{ border: 1px solid #e2e8f0; padding: 10px; text-align: left; vertical-align: top; font-size: 13px; }}
    th {{ background: #f8fafc; }}
    .sev {{ font-weight: 700; font-size: 11px; padding: 2px 6px; border-radius: 4px; }}
    .sev-critical {{ background: #fee2e2; color: #991b1b; }}
    .sev-high {{ background: #ffedd5; color: #9a3412; }}
    .sev-medium {{ background: #fef3c7; color: #92400e; }}
    .sev-low {{ background: #e0f2fe; color: #075985; }}
    .sev-info {{ background: #f1f5f9; color: #334155; }}
    .disclaimer {{ margin-top: 32px; padding: 12px; background: #f8fafc; border: 1px solid #cbd5e1; font-size: 12px; color: #475569; }}
  </style>
</head>
<body>
  <h1>SurfaceWatch External Attack-Surface Report</h1>
  <div class="meta">
    Domain: <strong>{html.escape(domain.name)}</strong> &middot;
    Generated: {generated_at} &middot;
    Verification: {html.escape(domain.verified_method or "unverified")}
  </div>

  <div class="summary">
    <div class="card"><div class="label">Risk Score</div><div class="value">{score}/100 ({grade})</div></div>
    <div class="card"><div class="label">Total Findings</div><div class="value">{len(findings)}</div></div>
    <div class="card"><div class="label">New Since Last</div><div class="value">{diff.counts['new']}</div></div>
    <div class="card"><div class="label">Resolved</div><div class="value">{diff.counts['resolved']}</div></div>
  </div>

  <h2>Findings &amp; Remediation</h2>
  <table>
    <thead>
      <tr><th>Severity</th><th>Host</th><th>Check</th><th>Details &amp; Remediation</th></tr>
    </thead>
    <tbody>
      {findings_table}
    </tbody>
  </table>

  <div class="disclaimer">
    Defensive-use report generated by SurfaceWatch. Only scan domains you own or have explicit written permission to test.
  </div>
</body>
</html>
"""


def generate_pdf_report(
    domain: Domain,
    scan: Scan | None,
    findings: list[FindingRecord],
    diff: DiffOut,
) -> bytes:
    pdf = FPDF()
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()

    pdf.set_font("Helvetica", "B", 16)
    pdf.cell(0, 10, _safe_pdf_text(f"SurfaceWatch Report: {domain.name}"), new_x="LMARGIN", new_y="NEXT")

    score = scan.risk_score if scan else domain.latest_risk_score
    grade = risk_grade_label(score)
    generated_at = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    pdf.set_font("Helvetica", "", 10)
    pdf.cell(
        0,
        7,
        _safe_pdf_text(
            f"Generated: {generated_at} | Risk Score: {score}/100 ({grade}) | "
            f"New: {diff.counts['new']} | Resolved: {diff.counts['resolved']}"
        ),
        new_x="LMARGIN",
        new_y="NEXT",
    )
    pdf.ln(4)

    if not findings:
        pdf.set_font("Helvetica", "", 11)
        pdf.cell(0, 8, "No findings recorded for this domain yet.", new_x="LMARGIN", new_y="NEXT")
    else:
        for idx, f in enumerate(findings, start=1):
            pdf.set_font("Helvetica", "B", 11)
            pdf.multi_cell(
                0,
                6,
                _safe_pdf_text(f"{idx}. [{f.severity.upper()}] {f.title} ({f.host})"),
                new_x="LMARGIN",
                new_y="NEXT",
            )
            pdf.set_font("Helvetica", "", 9)
            pdf.multi_cell(0, 5, _safe_pdf_text(f"Why it matters: {f.explanation}"), new_x="LMARGIN", new_y="NEXT")
            pdf.multi_cell(0, 5, _safe_pdf_text(f"Evidence: {f.evidence}"), new_x="LMARGIN", new_y="NEXT")
            pdf.multi_cell(0, 5, _safe_pdf_text(f"How to fix: {f.remediation}"), new_x="LMARGIN", new_y="NEXT")
            pdf.ln(3)

    pdf.ln(4)
    pdf.set_font("Helvetica", "I", 8)
    pdf.multi_cell(
        0,
        5,
        "Disclaimer: SurfaceWatch is a defensive monitor. Only scan domains you own or are authorized to test.",
        new_x="LMARGIN",
        new_y="NEXT",
    )
    return bytes(pdf.output())
