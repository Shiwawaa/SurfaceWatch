def generate_pdf_report(
    domain: Domain,
    scan: Scan | None,
    findings: list[FindingRecord],
    diff: DiffOut,
    lang: str = "en",
) -> bytes:
    s = _tr(lang)
    pdf = FPDF()
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()

    pdf.set_font("Helvetica", "B", 16)
    pdf.cell(0, 10, _safe_pdf_text(f"{s['pdf_heading']}: {domain.name}"), new_x="LMARGIN", new_y="NEXT")

    score = scan.risk_score if scan else domain.latest_risk_score
    grade = _grade_label(score, lang)
    generated_at = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    pdf.set_font("Helvetica", "", 10)
    pdf.cell(
        0,
        7,
        _safe_pdf_text(
            f"{s['generated']}: {generated_at} | {s['risk_score']}: {score}/100 ({grade}) | "
            f"{s['new_short']}: {diff.counts['new']} | {s['resolved']}: {diff.counts['resolved']}"
        ),
        new_x="LMARGIN",
        new_y="NEXT",
    )
    pdf.ln(4)

    if not findings:
        pdf.set_font("Helvetica", "", 11)
        pdf.cell(0, 8, _safe_pdf_text(s["no_findings_pdf"]), new_x="LMARGIN", new_y="NEXT")
    else:
        for idx, f in enumerate(findings, start=1):
            pdf.set_font("Helvetica", "B", 11)
            pdf.multi_cell(
                0,
                6,
                _safe_pdf_text(f"{idx}. [{_sev_label(f.severity, lang)}] {f.title} ({f.host})"),
                new_x="LMARGIN",
                new_y="NEXT",
            )
            pdf.set_font("Helvetica", "", 9)
            pdf.multi_cell(0, 5, _safe_pdf_text(f"{s['why_matters']}: {f.explanation}"), new_x="LMARGIN", new_y="NEXT")
            pdf.multi_cell(0, 5, _safe_pdf_text(f"{s['evidence']}: {f.evidence}"), new_x="LMARGIN", new_y="NEXT")
            pdf.multi_cell(0, 5, _safe_pdf_text(f"{s['how_to_fix']}: {f.remediation}"), new_x="LMARGIN", new_y="NEXT")
            pdf.ln(3)

    pdf.ln(4)
    pdf.set_font("Helvetica", "I", 8)
    pdf.multi_cell(
        0,
        5,
        _safe_pdf_text(s["disclaimer_pdf"]),
        new_x="LMARGIN",
        new_y="NEXT",
    )
    return bytes(pdf.output())
